function initialLang() {
  try {
    const saved = localStorage.getItem("bikefit.lang");
    if (saved in STRINGS) return saved;
  } catch { /* storage blocked */ }
  return (navigator.language || "en").toLowerCase().startsWith("de") ? "de" : "en";
}

export let lang = initialLang();

export function setLang(value) {
  lang = value in STRINGS ? value : "en";
  try { localStorage.setItem("bikefit.lang", lang); } catch { /* storage blocked */ }
  document.documentElement.lang = lang;
}

// t("key", {n: 2}) fills {n}; function entries get the params passed.
export function t(key, params = {}) {
  const v = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (typeof v === "function") return v(...Object.values(params));
  if (typeof v !== "string") return v;
  return v.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
}

